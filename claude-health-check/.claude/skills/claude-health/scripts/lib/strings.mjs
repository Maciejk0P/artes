export const STRINGS = { en: { ...en, ...uiEn }, sk: { ...sk, ...uiSk } };

export function assertLang(lang) {
  if (!LANGS.includes(lang)) throw new Error(`Unknown language "${lang}"; use one of: ${LANGS.join(', ')}`);
  return lang;
}

export function t(lang, key, params = {}) {
  const template = STRINGS[assertLang(lang)][key];
  if (template === undefined) throw new Error(`Unknown string "${key}" for language "${lang}"`);
  return template.replace(/\{(\w+)\}/g, (_, name) => {
    if (params[name] === undefined || params[name] === null) {
      throw new Error(`String "${key}" needs a value for {${name}}`);
    }
    return String(params[name]);
  });
}
