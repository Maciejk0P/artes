// Renders checks.md of part 2 (the prompt skill in .claude/skills/claude-health-prompt) from what
// part 1 runs: the lists of checks.mjs, the numbers of lib/facts.mjs, the titles and reasons of
// lib/strings.mjs and the measures of lib/catalogue.mjs. Nothing in that file is written by hand,
// so the two parts cannot be told different things.
//
//   node prompt-catalogue.mjs            print the file
//   node prompt-catalogue.mjs --write    write it into the folder of part 2
//   node prompt-catalogue.mjs --check    exit 1 when the file there is not what this prints

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CANDIDATE_CHECKS, CHECKS, REVIEW_CHECKS } from './checks.mjs';
import { CATALOGUE } from './lib/catalogue.mjs';
import { parseArgs, runCli } from './lib/cli.mjs';
import { FACTS, HOOK_EVENTS, LIMITS, SOURCES } from './lib/facts.mjs';
import { LANGS, t } from './lib/strings.mjs';

const [EN, SK] = LANGS;
const here = path.dirname(fileURLToPath(import.meta.url));
export const PROMPT_SKILL_DIR = path.resolve(here, '..', '..', 'claude-health-prompt');
export const CATALOGUE_FILE = path.join(PROMPT_SKILL_DIR, 'checks.md');

const LISTS = [
  ['finding', 'check', CHECKS, 'Findings: what a program can prove. Report only what you measured.'],
  ['candidate', 'candidate', CANDIDATE_CHECKS, 'Candidates: found by wording alone. Each one is read before anything is said about it.'],
  ['review', 'review', REVIEW_CHECKS, 'To review: proposes no change.'],
];

// The value a measure or a reason names as {name}.
function valueOf(name, entry) {
  if (name === 'limit') return LIMITS[entry.limit].value;
  if (name === 'fileLimit') return LIMITS.memoryFileLines.value;
  if (name === 'checkedOn') return FACTS.checkedOn;
  if (name === 'list') return 'deny (or ask)';
  if (name === 'hookEvents') return HOOK_EVENTS.join(', ');
  if (name.endsWith('Source')) return SOURCES[name.slice(0, -'Source'.length)];
  if (LIMITS[name]) return LIMITS[name].value;
  throw new Error(`lib/catalogue.mjs names {${name}}, which has no value`);
}

const fill = (text, entry) => text.replace(/\{(\w+)\}/g, (_, name) => String(valueOf(name, entry)));

export function renderCatalogue() {
  const all = [...CHECKS, ...CANDIDATE_CHECKS, ...REVIEW_CHECKS];
  const missing = all.filter((id) => !CATALOGUE[id]);
  const extra = Object.keys(CATALOGUE).filter((id) => !all.includes(id));
  if (missing.length || extra.length) {
    throw new Error(`lib/catalogue.mjs and checks.mjs disagree: missing ${missing.join(', ') || 'none'}; not a check ${extra.join(', ') || 'none'}`);
  }

  const out = [
    '<!-- Generated by .claude/skills/claude-health/scripts/prompt-catalogue.mjs from checks.mjs,',
    '     lib/catalogue.mjs, lib/facts.mjs and lib/strings.mjs. Do not edit: change those and run',
    '     node .claude/skills/claude-health/scripts/prompt-catalogue.mjs --write -->',
    '',
    '# The checks',
    '',
    `The same ${all.length} checks as the program (part 1), in the same order, with the same ids, limits and severities.`,
    `The documented facts were read on ${FACTS.checkedOn}.`,
    '',
    '## Limits',
    '',
    '| name | value | documented | source |',
    '|---|---|---|---|',
    ...Object.entries(LIMITS).map(
      ([name, limit]) =>
        `| ${name} | ${limit.value} | ${limit.documented ? (limit.verified === false ? 'yes, carried over' : 'yes') : 'no, a default of this tool'} | ${limit.source ?? '-'} |`,
    ),
    '',
  ];
  for (const [list, strings, ids, intro] of LISTS) {
    out.push(`## ${list === 'finding' ? 'Findings' : list === 'candidate' ? 'Candidates' : 'To review'} (${ids.length})`, '', intro, '');
    for (const id of ids) {
      const entry = CATALOGUE[id];
      const params = new Proxy({}, { get: (_, name) => (typeof name === 'string' ? valueOf(name, entry) : undefined) });
      out.push(`### ${id}`, '');
      out.push(`- Title: ${t(EN, `${strings}.${id}.title`)} / ${t(SK, `${strings}.${id}.title`)}`);
      if (entry.severity) out.push(`- Severity: ${entry.severity.length > 1 ? `${entry.severity.join(' or ')}, as the measure says` : entry.severity[0]}`);
      if (entry.kind) out.push(`- Suggests: ${entry.kind}`);
      out.push(`- Measure: ${fill(entry.measure, entry)}`);
      out.push(`- Why: ${t(EN, `${strings}.${id}.why`, params)}`);
      out.push('');
    }
  }
  return `${out.join('\n').trimEnd()}\n`;
}

runCli(import.meta.url, (argv) => {
  const args = parseArgs(argv, { write: 'boolean', check: 'boolean' });
  const text = renderCatalogue();
  if (args.write) {
    writeFileSync(CATALOGUE_FILE, text);
    return { out: CATALOGUE_FILE, lines: text.split('\n').length - 1 };
  }
  if (args.check) {
    let current = null;
    try {
      current = readFileSync(CATALOGUE_FILE, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      // A missing file is the same answer as a stale one.
    }
    if (current !== text) throw new Error(`${CATALOGUE_FILE} is not what the catalogue renders. Run: node prompt-catalogue.mjs --write`);
    return { ok: true };
  }
  process.stdout.write(text);
  return undefined;
});
